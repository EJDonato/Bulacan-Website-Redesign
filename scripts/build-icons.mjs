// Generates src/styles/icon-tokens.css: one `--icon-<name>` data-URI token per Lucide icon used.
// Run: node scripts/build-icons.mjs   (add a name below, then re-run)
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const names = [
  // chrome
  'menu', 'search', 'x', 'chevron-down', 'chevron-up', 'chevron-left', 'chevron-right', 'arrow-right',
  'external-link', 'house', 'info', 'check', 'play', 'pause', 'qr-code', 'quote',
  // quick links (content.md §4)
  'map-pinned', 'building-2', 'file-check-2', 'briefcase', 'trending-up', 'hospital',
  // inner pages
  'file-text', 'phone', 'mail', 'clock', 'calendar', 'download', 'map-pin', 'award', 'shield-check', 'landmark',
];

const encode = (svg) =>
  svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/ class="[^"]*"/, '')
    .replace(/stroke-width="2"/, 'stroke-width="1.75"') // design-system §7
    .trim()
    .replace(/"/g, "'")
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/#/g, '%23');

const lines = [];
for (const name of names) {
  const svg = await readFile(join(ROOT, 'node_modules', 'lucide-static', 'icons', `${name}.svg`), 'utf8');
  lines.push(`  --icon-${name}: url("data:image/svg+xml,${encode(svg)}");`);
}

const css = `/* Generated by scripts/build-icons.mjs from lucide-static. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`;
await writeFile(join(ROOT, 'src', 'styles', 'icon-tokens.css'), css);
console.log(`wrote ${names.length} icon tokens`);
